test_that("plot methods draw without error", {
  fit <- fit_binary(small_binary(n = 300, K = 4))
  pdf(NULL)
  on.exit(dev.off(), add = TRUE)
  res <- aste(fit, newdata = data.frame(x = c(-1, 1)), K = 1:4)
  expect_null(plot(res))
  expect_null(plot(res, effects = "DASTE", profiles = 2, band = FALSE))
  one <- aste(fit, newdata = data.frame(x = 0))
  expect_null(plot(one, effects = c("STE1", "STE2", "DASTE")))
  e <- easte(fit, K = 1:4)
  expect_null(plot(e))
  expect_null(plot(easte(fit), effects = "DEASTE"))
  expect_error(plot(res, profiles = 3), "row numbers")
  expect_error(plot(res, effects = "ESTE1"), "should be one of")
})
